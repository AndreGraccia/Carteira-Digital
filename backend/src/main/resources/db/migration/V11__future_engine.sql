-- Wall.ia "Futuro": user answers about detected recurrences, and the card/loan data
-- received from Open Finance (sandbox) that feeds the deterministic projection.

CREATE TABLE recurrence_decision
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT                   NOT NULL,
    pattern_key VARCHAR(120)             NOT NULL,
    status      VARCHAR(20)              NOT NULL,
    category    VARCHAR(20)              NOT NULL,
    decided_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_recurrence_decision PRIMARY KEY (id),
    CONSTRAINT fk_recurrence_decision_user FOREIGN KEY (user_id) REFERENCES public."user" (id),
    CONSTRAINT recurrence_decision_user_pattern_key UNIQUE (user_id, pattern_key),
    CONSTRAINT recurrence_decision_status_check CHECK (status IN ('CONFIRMED', 'REJECTED'))
);

COMMENT ON TABLE recurrence_decision IS
    'Resposta do usuario a uma recorrencia detectada. Somente CONFIRMED entra nas projecoes.';

CREATE TABLE credit_card
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT                   NOT NULL,
    external_id     VARCHAR(160)             NOT NULL,
    institution     VARCHAR(100)             NOT NULL,
    name            VARCHAR(60)              NOT NULL,
    last_digits     VARCHAR(4),
    credit_limit    NUMERIC(14, 2)           NOT NULL,
    closing_day     SMALLINT                 NOT NULL,
    due_day         SMALLINT                 NOT NULL,
    last_synced_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_credit_card PRIMARY KEY (id),
    CONSTRAINT fk_credit_card_user FOREIGN KEY (user_id) REFERENCES public."user" (id),
    CONSTRAINT credit_card_user_external_key UNIQUE (user_id, external_id),
    CONSTRAINT credit_card_days_check CHECK (closing_day BETWEEN 1 AND 31 AND due_day BETWEEN 1 AND 31),
    CONSTRAINT credit_card_limit_check CHECK (credit_limit >= 0)
);

CREATE TABLE card_charge
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    card_id            BIGINT         NOT NULL,
    external_id        VARCHAR(160)   NOT NULL,
    description        VARCHAR(120)   NOT NULL,
    purchase_date      DATE           NOT NULL,
    total_amount       NUMERIC(14, 2) NOT NULL,
    installment_amount NUMERIC(14, 2) NOT NULL,
    installments       SMALLINT       NOT NULL,
    first_invoice      DATE           NOT NULL,
    CONSTRAINT pk_card_charge PRIMARY KEY (id),
    CONSTRAINT fk_card_charge_card FOREIGN KEY (card_id) REFERENCES credit_card (id),
    CONSTRAINT card_charge_card_external_key UNIQUE (card_id, external_id),
    CONSTRAINT card_charge_amounts_check CHECK (total_amount > 0 AND installment_amount > 0 AND installments BETWEEN 1 AND 48)
);

COMMENT ON COLUMN card_charge.first_invoice IS
    'Primeiro dia do mes de vencimento da fatura que contem a parcela 1. As faturas sao recalculadas a partir das compras.';

CREATE TABLE loan
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id            BIGINT                   NOT NULL,
    external_id        VARCHAR(160)             NOT NULL,
    institution        VARCHAR(100)             NOT NULL,
    product            VARCHAR(80)              NOT NULL,
    contracted_amount  NUMERIC(14, 2)           NOT NULL,
    outstanding_balance NUMERIC(14, 2)          NOT NULL,
    installment_amount NUMERIC(14, 2)           NOT NULL,
    installments_total SMALLINT                 NOT NULL,
    installments_paid  SMALLINT                 NOT NULL,
    next_due_date      DATE,
    annual_rate        NUMERIC(9, 4),
    last_synced_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_loan PRIMARY KEY (id),
    CONSTRAINT fk_loan_user FOREIGN KEY (user_id) REFERENCES public."user" (id),
    CONSTRAINT loan_user_external_key UNIQUE (user_id, external_id),
    CONSTRAINT loan_installments_check CHECK (installments_paid >= 0 AND installments_paid <= installments_total),
    CONSTRAINT loan_amounts_check CHECK (outstanding_balance >= 0 AND installment_amount > 0)
);

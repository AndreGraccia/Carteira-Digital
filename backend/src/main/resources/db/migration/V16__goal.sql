-- Monthly savings goals set by the user. Each one becomes a commitment in the projection, so the
-- daily limit already leaves the goal out ("how much can I spend without giving up the goal?").
CREATE TABLE goal
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id        BIGINT                   NOT NULL,
    name           VARCHAR(60)              NOT NULL,
    monthly_amount NUMERIC(12, 2)           NOT NULL,
    day_of_month   SMALLINT                 NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_goal PRIMARY KEY (id),
    CONSTRAINT fk_goal_user FOREIGN KEY (user_id) REFERENCES public."user" (id),
    CONSTRAINT goal_amount_check CHECK (monthly_amount > 0 AND monthly_amount <= 1000000),
    CONSTRAINT goal_day_check CHECK (day_of_month BETWEEN 1 AND 31)
);

CREATE INDEX idx_goal_user ON goal (user_id);

COMMENT ON TABLE goal IS
    'Meta mensal definida pelo usuario. Entra na projecao como compromisso confirmado por ele.';

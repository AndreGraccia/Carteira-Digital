-- Who called an administrative endpoint, when, and with what result. Administrators can list every
-- user's wallets and transactions; this trail makes that access visible. Denied attempts are kept too.
-- Only method, path and status are stored: never request bodies or query strings.
CREATE TABLE admin_audit
(
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    actor_id BIGINT                   NOT NULL,
    method   VARCHAR(10)              NOT NULL,
    path     VARCHAR(200)             NOT NULL,
    status   INTEGER                  NOT NULL,
    at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_admin_audit PRIMARY KEY (id),
    CONSTRAINT fk_admin_audit_actor FOREIGN KEY (actor_id) REFERENCES public."user" (id)
);

CREATE INDEX idx_admin_audit_at ON admin_audit (at);

COMMENT ON TABLE admin_audit IS
    'Trilha de acesso a endpoints administrativos, inclusive tentativas negadas. Somente insercao.';

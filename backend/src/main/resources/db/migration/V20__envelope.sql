-- Envelopes: part of today's balance the user sets aside for something the projection does not know
-- (a trip, the car tax, an emergency fund). No money moves; the total works as a floor, so the daily
-- limit answers "how much can I spend without touching my envelopes?". Replaces the "Movimentar" screen,
-- whose transfers had no real use (local wallets never receive money).
CREATE TABLE envelope
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT                   NOT NULL,
    name       VARCHAR(60)              NOT NULL,
    amount     NUMERIC(12, 2)           NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_envelope PRIMARY KEY (id),
    CONSTRAINT fk_envelope_user FOREIGN KEY (user_id) REFERENCES public."user" (id),
    CONSTRAINT envelope_amount_check CHECK (amount > 0 AND amount <= 1000000)
);

CREATE INDEX idx_envelope_user ON envelope (user_id);

COMMENT ON TABLE envelope IS
    'Dinheiro do saldo atual separado pelo usuario. Nada se move; o total vira piso do limite diario.';

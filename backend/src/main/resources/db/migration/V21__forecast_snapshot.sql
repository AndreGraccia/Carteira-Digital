-- One row per user per day the bank data was synced: the real balance that day and, when the user has
-- confirmed at least one recurrence, the 30-day projection made from it. A later sync compares its real
-- balance with what was projected 7 to 30 days before. That is the "how right was Wall.ia" score and the
-- north-star metric (negative days predicted that did not happen).
CREATE TABLE forecast_snapshot
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT                   NOT NULL,
    taken_on   DATE                     NOT NULL,
    balance    NUMERIC(14, 2)           NOT NULL,
    -- Balances from taken_on to taken_on + 30, separated by ";". NULL when nothing was confirmed yet:
    -- a projection without the user's answers is not a forecast worth grading.
    projection TEXT,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_forecast_snapshot PRIMARY KEY (id),
    CONSTRAINT fk_forecast_snapshot_user FOREIGN KEY (user_id) REFERENCES public."user" (id),
    CONSTRAINT uq_forecast_snapshot_day UNIQUE (user_id, taken_on)
);

COMMENT ON TABLE forecast_snapshot IS
    'Saldo real e projecao de 30 dias guardados a cada sincronizacao, para medir quanto a previsao acertou.';

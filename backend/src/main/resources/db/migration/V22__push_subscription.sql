-- Browsers where the user turned on push alerts. The keys only encrypt what goes to that browser;
-- the endpoint belongs to the browser's push service (Google, Mozilla, Apple, Microsoft).
CREATE TABLE push_subscription
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT                   NOT NULL,
    endpoint   VARCHAR(1000)            NOT NULL,
    p256dh     VARCHAR(100)             NOT NULL,
    auth       VARCHAR(50)              NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_push_subscription PRIMARY KEY (id),
    CONSTRAINT fk_push_subscription_user FOREIGN KEY (user_id) REFERENCES public."user" (id),
    -- One browser, one owner: subscribing again from another account moves it.
    CONSTRAINT uq_push_subscription_endpoint UNIQUE (endpoint)
);

CREATE INDEX idx_push_subscription_user ON push_subscription (user_id);

COMMENT ON TABLE push_subscription IS
    'Navegadores inscritos para receber o alerta de saldo negativo por push.';

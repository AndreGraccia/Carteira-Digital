-- Dados públicos do Banco Central guardados uma vez por dia (ADR 0010): taxas por instituição para pessoa física
-- (API Olinda taxaJuros v2, TaxasJurosDiariaPorInicioPeriodo) e indicadores do SGS (CDI, IPCA em 12 meses, Selic).
-- A tela mostra a fonte e a data; sem dado, o app volta ao teto legal.
CREATE TABLE market_rate
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    modality     VARCHAR(20)  NOT NULL,
    period_start DATE         NOT NULL,
    period_end   DATE         NOT NULL,
    cnpj8        VARCHAR(8)   NOT NULL,
    institution  VARCHAR(120) NOT NULL,
    monthly_rate NUMERIC(9, 4)  NOT NULL,
    annual_rate  NUMERIC(10, 4) NOT NULL,
    CONSTRAINT pk_market_rate PRIMARY KEY (id),
    CONSTRAINT market_rate_key UNIQUE (modality, period_start, cnpj8),
    CONSTRAINT market_rate_modality_check CHECK (modality IN ('OVERDRAFT', 'CARD_REVOLVING', 'PERSONAL_LOAN'))
);

CREATE TABLE market_indicator
(
    code           VARCHAR(20)              NOT NULL,
    reference_date DATE                     NOT NULL,
    value          NUMERIC(12, 6)           NOT NULL,
    fetched_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_market_indicator PRIMARY KEY (code)
);

function normalizeLanguage(language) {
  return language?.toLowerCase().split('-')[0];
}

let savedLanguage;
try {
  savedLanguage = normalizeLanguage(localStorage.getItem('appLanguage'));
} catch {
  // Language selection also works when storage is disabled.
}
const browserLanguage = normalizeLanguage(navigator.language) === 'pt' ? 'pt' : 'en';

function syncLanguage(language) {
  const normalized = normalizeLanguage(language) === 'en' ? 'en' : 'pt';
  document.documentElement.lang = normalized === 'pt' ? 'pt-BR' : 'en';
  try {
    localStorage.setItem('appLanguage', normalized);
  } catch {
    // Keep the selected language for the current session.
  }
}

i18n.on('languageChanged', syncLanguage);
i18n.use(initReactI18next).init({
  resources,
  lng: ['pt', 'en'].includes(savedLanguage) ? savedLanguage : browserLanguage,
  fallbackLng: 'pt',
  supportedLngs: ['pt', 'en'],
  interpolation: {
    escapeValue: false,
  },
});

export default i18n;
